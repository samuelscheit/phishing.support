/**
 * What a page that is nothing but an error says, read from its content,
 * never from its HTTP status: kits serve live pages under 403, 404 or 500,
 * and servers answer 200 with a bare "Not Found". Shared by the capture (a
 * network that was blocked tries the next one), liveness (a host's bare
 * not-found page is a removal) and the redirector watch.
 *
 * Two tiers. A vendor's own block or origin-error page (Cloudflare, Akamai,
 * Imperva, Sucuri, DataDome, AWS WAF / CloudFront) is told by signatures no
 * lure carries together, at any length. Anything else counts only when it is
 * a bare server page: short, with no form, field, button or link to act on,
 * saying nothing but a server's error. A lure's "Access denied: your session
 * has expired. View Document" is a page of the site.
 */
export type BareErrorPage = "not_found" | "server_error" | "blocked";

type ErrorPageContent = { title?: string; text?: string; html?: string; headers?: Readonly<Record<string, string>> };

/** More visible text than this is a page of the site, unless a vendor's signature says otherwise. */
const MAX_ERROR_TEXT = 600;

/** Each vendor block page by the signatures that only it shows together; `said` is its title and visible text, `html` its markup. */
const VENDOR_BLOCKS: Array<(said: string, html: string) => boolean> = [
	// Cloudflare: its block page's title, its error box, or its block headline or a 10xx error with its Ray ID.
	(said, html) => /attention required!?\s*\|\s*cloudflare/i.test(said) || /\bcf-error-details\b/i.test(html)
		|| ((/\berror (?:code:?\s*)?10(?:0\d|1\d|20)\b|sorry, you have been blocked/i.test(said)) && /\bray id\b/i.test(said)),
	// Akamai: Access Denied with its reference number.
	(said) => /access denied/i.test(said) && /reference\s*#\s*[\d.a-f]{6,}/i.test(said),
	// Imperva / Incapsula.
	(said) => /incapsula incident id/i.test(said),
	// Sucuri Website Firewall (CloudProxy).
	(said) => /sucuri website firewall/i.test(said) && /access denied|block id|blocked/i.test(said),
	// DataDome's block page, served from its captcha host.
	(said, html) => /captcha-delivery\.com|\bdatadome\b/i.test(html) && /\b(?:blocked|access (?:is )?(?:temporarily )?restricted)\b/i.test(said),
	// AWS WAF through CloudFront.
	(said) => /request (?:could not be satisfied|blocked)/i.test(said) && /generated by cloudfront|request id:/i.test(said),
];
/** Cloudflare's own page for an origin that failed it (520–530). */
const VENDOR_ORIGIN_ERROR = (said: string) => /\berror (?:code:?\s*)?5(?:2\d|30)\b/i.test(said) && /\bcloudflare\b/i.test(said);

/** A bare server's block, as its title or first words say it: nginx, Apache, IIS, LiteSpeed, Varnish, Envoy, HAProxy. */
const GENERIC_BLOCKED = /^(?:(?:error\s*)?403\b[\s:-]*(?:forbidden)?|forbidden\b|access denied\.?$|access forbidden\b|request forbidden\b|rbac: access denied)/i;
/** The server or its upstream failing. */
const GENERIC_SERVER_ERROR = /internal server error|bad gateway|service (?:temporarily )?unavailable|gateway time-?out|web server is down|origin is unreachable|upstream (?:connect error|request timeout)|no healthy upstream|\berror (?:code:?\s*)?5(?:0\d|2\d|30)\b/i;
/** The page is gone. */
const GENERIC_NOT_FOUND = /\b404\b|\bnot found\b|\b410 gone\b|^\s*gone\b|page (?:not found|doesn'?t exist|does not exist)|unavailable for legal reasons|no such file/i;

/** Any control a visitor can enter data in, or a form: a page with one is the site. */
const DATA_ENTRY = /<(?:form|textarea|select)\b|<input\b(?![^>]*\btype\s*=\s*["']?hidden\b)/i;
/** Anything to act on: a button, or a link that goes somewhere. */
const ACTION = /<button\b|<a\b[^>]*\bhref\s*=\s*(?!["']?(?:#|javascript:)|["']\s*["'])/i;

/** The text a browser shows of an HTML page: no scripts, styles or markup, entities of whitespace and markup decoded, whitespace collapsed. */
export function visibleText(html: string): string {
	return html
		.replace(/<(script|style|noscript|template|head)\b[\s\S]*?<\/\1\s*>/gi, " ")
		.replace(/<[^>]*>/g, " ")
		.replace(/&nbsp;|&#160;/gi, " ")
		.replace(/&amp;/gi, "&")
		.replace(/&lt;/gi, "<")
		.replace(/&gt;/gi, ">")
		.replace(/&quot;/gi, "\"")
		.replace(/&#39;|&apos;/gi, "'")
		.replace(/\s+/g, " ")
		.trim();
}

function htmlTitle(html: string): string {
	return visibleText(html.match(/<title\b[^>]*>([\s\S]*?)<\/title\s*>/i)?.[1] ?? "");
}

/**
 * The kind of bare error page this is, or undefined when it is anything
 * else: a page with a form or a field, a page with real text or something to
 * act on, or an empty one (whose meaning the caller decides).
 */
export function classifyBareErrorPage(page: ErrorPageContent): BareErrorPage | undefined {
	const html = page.html ?? "";
	if (DATA_ENTRY.test(html)) return undefined;
	const text = (page.text ?? visibleText(html)).replace(/\s+/g, " ").trim();
	const title = (page.title ?? htmlTitle(html)).replace(/\s+/g, " ").trim();
	if (!text && !title) return undefined;
	const said = [title, text].filter(Boolean).join("\n");
	if (/^block$/i.test(page.headers?.["x-amzn-waf-action"]?.trim() ?? "")) return "blocked";
	if (VENDOR_ORIGIN_ERROR(said)) return "server_error";
	if (VENDOR_BLOCKS.some((matches) => matches(said, html))) return "blocked";
	// A bare server page: short, nothing to act on.
	if (text.length > MAX_ERROR_TEXT || ACTION.test(html)) return undefined;
	if (GENERIC_BLOCKED.test(title) || GENERIC_BLOCKED.test(text)) return "blocked";
	if (GENERIC_SERVER_ERROR.test(said)) return "server_error";
	if (GENERIC_NOT_FOUND.test(said)) return "not_found";
	return undefined;
}
